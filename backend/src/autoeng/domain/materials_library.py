"""Extended material library: every vehicle system, not just the engine.

Typical handbook values (ASM Handbooks, MatWeb, EN/ISO/SAE standards and supplier datasheets) for one named
condition, each with a tolerance that reflects the spread between sources and suppliers. Where no reliable figure
exists a property is left out rather than guessed. Composites and polymers are anisotropic or temperature
sensitive; their values are for the stated layup or a dry, room-temperature condition.
"""

