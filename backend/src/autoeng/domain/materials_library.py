def _p(value: float, tol: float, ref: str = HANDBOOK) -> Param:
    return P(value, Source.LITERATURE, tol, ref)


def _m(id, name, category, condition, uses, props, processes=(), notes=""):
    return {"id": id, "name": name, "category": category, "condition": condition, "uses": list(uses),
            "properties": {k: (_p(*v) if isinstance(v, tuple) else v) for k, v in props.items()},
            "processes": list(processes), "notes": notes}


